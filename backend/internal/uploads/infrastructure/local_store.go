package infrastructure

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ecommerce/backend/internal/uploads/domain"
	"github.com/ecommerce/backend/pkg/errors"
)

// LocalStore keeps pictures in a folder on the server (a Docker volume in production).
type LocalStore struct {
	dir        string
	publicPath string // URL prefix the files are served under, e.g. "/uploads"
}

// NewLocalStore creates the folder if needed and returns a store writing into it.
func NewLocalStore(dir, publicPath string) (*LocalStore, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("create upload folder %q: %w", dir, err)
	}
	return &LocalStore{dir: dir, publicPath: "/" + strings.Trim(publicPath, "/")}, nil
}

// Dir is the folder files are written to (served as static files by the API).
func (s *LocalStore) Dir() string { return s.dir }

// PublicPath is the URL prefix files are served under.
func (s *LocalStore) PublicPath() string { return s.publicPath }

var _ domain.Store = (*LocalStore)(nil)

// Save writes the file. The name is generated by the service, but is still checked here so
// a bad name can never escape the folder.
func (s *LocalStore) Save(_ context.Context, name string, data []byte) error {
	if name == "" || name != filepath.Base(name) || strings.ContainsAny(name, `/\`) {
		return errors.New("VALIDATION_ERROR", "invalid file name", 422)
	}
	path := filepath.Join(s.dir, name)
	// O_EXCL: never overwrite an existing file.
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return errors.Wrap("INTERNAL_ERROR", "could not save the picture", 500, err)
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return errors.Wrap("INTERNAL_ERROR", "could not save the picture", 500, err)
	}
	if err := f.Close(); err != nil {
		return errors.Wrap("INTERNAL_ERROR", "could not save the picture", 500, err)
	}
	return nil
}

// URL returns the path the picture can be loaded from.
func (s *LocalStore) URL(name string) string { return s.publicPath + "/" + name }
