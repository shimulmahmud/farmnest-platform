// Package domain holds the rules for uploaded pictures.
package domain

import (
	"bytes"
	"context"
	"fmt"
	"image"
	_ "image/gif"  // register decoders so image.DecodeConfig can read the header
	_ "image/jpeg" //
	_ "image/png"  //
	"net/http"

	"github.com/ecommerce/backend/pkg/errors"
)

// Info describes a validated picture.
type Info struct {
	ContentType string
	Ext         string // ".jpg", ".png", ".gif" or ".webp" (from the real content, never from the file name)
	Width       int
	Height      int
	Size        int
}

// Validator decides whether an uploaded file is an acceptable picture.
type Validator struct {
	MaxBytes  int // largest file
	MaxPixels int // width x height limit (protects the server from decompression bombs)
}

// DefaultValidator allows pictures up to 8 MB and 40 megapixels.
func DefaultValidator() Validator { return Validator{MaxBytes: 8 << 20, MaxPixels: 40_000_000} }

func invalid(msg string) error { return errors.New("VALIDATION_ERROR", msg, 422) }

// Check looks at the file's actual bytes. Only JPEG, PNG, GIF and WebP pass; everything
// else (including SVG, which can carry scripts, and HTML renamed to .jpg) is rejected.
func (v Validator) Check(data []byte) (*Info, error) {
	if len(data) == 0 {
		return nil, invalid("the file is empty")
	}
	if len(data) > v.MaxBytes {
		return nil, invalid(fmt.Sprintf("the picture is too big (maximum %d MB)", v.MaxBytes>>20))
	}

	info := &Info{Size: len(data)}
	switch ct := http.DetectContentType(data); ct {
	case "image/jpeg":
		info.ContentType, info.Ext = ct, ".jpg"
	case "image/png":
		info.ContentType, info.Ext = ct, ".png"
	case "image/gif":
		info.ContentType, info.Ext = ct, ".gif"
	case "image/webp":
		info.ContentType, info.Ext = ct, ".webp"
	default:
		return nil, invalid("only JPG, PNG, GIF or WebP pictures can be uploaded")
	}

	// JPEG/PNG/GIF: confirm the file really is a picture and read its size.
	// (WebP is accepted on its signature; the standard library cannot read its header.)
	if info.Ext != ".webp" {
		cfg, _, err := image.DecodeConfig(bytes.NewReader(data))
		if err != nil {
			return nil, invalid("this file is not a valid picture")
		}
		if cfg.Width <= 0 || cfg.Height <= 0 || cfg.Width*cfg.Height > v.MaxPixels {
			return nil, invalid("the picture has too many pixels; please resize it before uploading")
		}
		info.Width, info.Height = cfg.Width, cfg.Height
	}
	return info, nil
}

// Store saves files and says where customers can load them from.
type Store interface {
	// Save writes the file under the given name (unique, generated by the service).
	Save(ctx context.Context, name string, data []byte) error
	// URL is the address stored on products. Local storage returns a path like /uploads/abc.jpg.
	URL(name string) string
}
